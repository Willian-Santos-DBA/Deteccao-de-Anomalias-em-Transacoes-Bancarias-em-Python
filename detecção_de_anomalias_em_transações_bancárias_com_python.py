"""**Ajuste de hiperparâmentros**

Testamos várias combinações para melhorar o modelo.
"""

from sklearn.model_selection import GridSearchCV
from xgboost import XGBClassifier

param_grid = {
    "max_depth": [3, 5],
    "n_estimators": [50, 100]
}


import pandas as pd

url = "https://storage.googleapis.com/download.tensorflow.org/data/creditcard.csv"

df = pd.read_csv(url)

df.head()

"""**Problema de classificação desbalanceada**

Transações Normais = 0

Transações Fraudulentas = 1

"Fraudes são raras, e isso faz com que o modelo possa ignorar a classe 1."
"""

